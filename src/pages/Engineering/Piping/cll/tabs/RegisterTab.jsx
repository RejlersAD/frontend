// ============================================================================
// Tab 1 — LINE REGISTER: KPI row, amber banner when stress file is missing,
// quick filter chips, full-width table, line detail right drawer.
// ============================================================================
import React, { useMemo, useState } from 'react';
import { useSearchParams } from 'react-router-dom';
import { useCll } from '../CllStore';
import { CAT_PILL, LINE_LIST_FIELDS, exportRegisterWorkbook } from '../cllFiles';

// §6C — URL filter chips: ?match=matched|conflict|missing|notinll and
// ?category=critical, set by the Upload Analysis tiles / distribution card.
const MATCH_FILTERS = {
  matched: { label: 'Matched', test: l => l.match_status === 'Matched' },
  conflict: { label: 'Conflicts', test: l => l.match_status === 'Conflict' },
  missing: { label: 'Missing criticality', test: l => l.match_status === 'Missing criticality' },
  notinll: { label: 'Not in line list', test: l => l.match_status === 'Not in line list' },
};

const MATCH_PILL = {
  'Matched': 'rd-pill-success',
  'Missing criticality': 'rd-pill-danger',
  'Not in line list': 'rd-pill-orange',
  'Conflict': 'rd-pill-warning',
};

const CHIPS = ['All', 'Stress critical', 'L1', 'Needs review'];

export function EmptyState() {
  const { setUploadDrawerOpen } = useCll();
  return (
    <div className="rd-card" style={{ padding: '3rem', textAlign: 'center' }}>
      <svg width="40" height="40" viewBox="0 0 24 24" fill="none" stroke="var(--rd-text-faint)" style={{ margin: '0 auto' }}>
        <path strokeLinecap="round" strokeLinejoin="round" strokeWidth="1.5" d="M12 16V4m0 0L8 8m4-4l4 4M4 20h16" />
      </svg>
      <p style={{ margin: '0.75rem 0 1.25rem', color: 'var(--rd-text-muted)' }}>
        Upload the Process Line List and Stress Criticality files to build the list
      </p>
      <div style={{ display: 'flex', gap: '0.75rem', justifyContent: 'center', flexWrap: 'wrap' }}>
        <button className="rd-btn rd-btn-primary" onClick={() => setUploadDrawerOpen(true)}>Upload Process Line List</button>
        <button className="rd-btn rd-btn-secondary" onClick={() => setUploadDrawerOpen(true)}>Upload Stress Criticality</button>
      </div>
    </div>
  );
}

function LineDrawer({ line, onClose }) {
  const { files } = useCll();
  if (!line) return null;
  const ROWS = [
    ['Line Number', line.line_number], ['Size', line.size], ['Fluid/Service', line.fluid],
    ['Pipe Class', line.pipe_class], ['From', line.from], ['To', line.to],
    ['P&ID No.', line.pid_no], ['Design Pressure', line.design_pressure],
    ['Design Temperature', line.design_temperature],
    ['Stress Category', line.stress_category], ['Criteria Basis', line.criteria_basis],
    ['Analysis Method', line.analysis_method], ['Responsible Engineer', line.responsible_engineer],
  ];
  return (
    <>
      <div className="rd-drawer-backdrop" onClick={onClose} />
      <aside className="rd-drawer" role="dialog" aria-label={`Line ${line.line_number}`}>
        <header className="rd-drawer-header">
          <span className="rd-mono">{line.line_number}</span>
          <button className="rd-btn rd-btn-ghost rd-btn-sm" onClick={onClose} aria-label="Close">✕</button>
        </header>
        <div className="rd-drawer-body">
          <div style={{ display: 'flex', gap: '0.5rem', marginBottom: '1rem' }}>
            <span className={`rd-pill ${CAT_PILL[line.stress_category] || 'rd-pill-neutral'}`}>{line.stress_category}</span>
            <span className={`rd-pill ${MATCH_PILL[line.match_status] || 'rd-pill-neutral'}`}>{line.match_status}</span>
          </div>
          <dl>
            {ROWS.map(([k, v]) => (
              <div key={k} style={{ display: 'flex', justifyContent: 'space-between', padding: '0.5rem 0', borderBottom: '1px solid var(--rd-border-soft)' }}>
                <dt className="rd-text-muted" style={{ fontSize: 'var(--rd-text-body)' }}>{k}</dt>
                <dd className="rd-mono" style={{ color: 'var(--rd-text)' }}>{v || '—'}</dd>
              </div>
            ))}
          </dl>
          <h4 className="rd-text-muted" style={{ fontSize: 'var(--rd-text-caption)', fontWeight: 600, margin: '1.25rem 0 0.5rem' }}>CRITICALITY BASIS</h4>
          <div style={{ fontSize: 'var(--rd-text-body)' }}>
            <div style={{ marginBottom: '0.5rem' }}>
              <span className={`rd-pill ${line.category_source === 'generated' ? 'rd-pill-info' : 'rd-pill-neutral'}`}>
                {line.category_source === 'generated' ? 'Auto-generated by RADAI' : 'From uploaded Stress Criticality file'}
              </span>
            </div>
            {line.criteria_basis && <p style={{ color: 'var(--rd-text)' }}>{line.criteria_basis}</p>}
            {line._generated?.sec73?.length > 0 && (
              <p className="rd-text-muted" style={{ fontSize: 'var(--rd-text-caption)', marginTop: 4 }}>
                Sec. 7.3 items: {line._generated.sec73.map(s => `${s.id} (${s.why})`).join('; ')}
              </p>
            )}
          </div>
          <h4 className="rd-text-muted" style={{ fontSize: 'var(--rd-text-caption)', fontWeight: 600, margin: '1.25rem 0 0.5rem' }}>SOURCE</h4>
          <div style={{ fontSize: 'var(--rd-text-caption)' }} className="rd-text-muted space-y-1">
            <div>Line list: <span className="rd-mono">{files.lineList?.name}</span> · sheet <span className="rd-mono">{files.lineList?.sheet}</span> · row <span className="rd-mono">{line._row}</span></div>
            {line._stress && (
              <div>Stress criticality: <span className="rd-mono">{files.stress?.name}</span> · sheet <span className="rd-mono">{files.stress?.sheet}</span> · row <span className="rd-mono">{line._stress._row}</span></div>
            )}
          </div>
        </div>
      </aside>
    </>
  );
}

export default function RegisterTab() {
  const { match, files } = useCll();
  const [chip, setChip] = useState('All');
  const [selected, setSelected] = useState(null);
  const [searchParams, setSearchParams] = useSearchParams();

  const matchFilter = MATCH_FILTERS[searchParams.get('match')] || null;
  const categoryCritical = searchParams.get('category') === 'critical';
  const clearUrlFilters = () => setSearchParams({}, { replace: true });

  const kpis = useMemo(() => {
    if (!match) return null;
    return {
      total: match.lines.length,
      critical: match.lines.filter(l => l.stress_category === 'L1').length,
      matched: match.summary.matched,
      missing: match.summary.missing,
      review: match.summary.missing + match.summary.conflicts + match.summary.notInLineList,
    };
  }, [match]);

  const filtered = useMemo(() => {
    if (!match) return [];
    let lines = match.lines;
    if (matchFilter) lines = lines.filter(matchFilter.test);
    if (categoryCritical) lines = lines.filter(l => ['L1', 'L2', 'L3'].includes(l.stress_category));
    switch (chip) {
      case 'Stress critical': return lines.filter(l => ['L1', 'L2'].includes(l.stress_category));
      case 'L1': return lines.filter(l => l.stress_category === 'L1');
      case 'Needs review': return lines.filter(l => l.match_status !== 'Matched');
      default: return lines;
    }
  }, [match, chip, matchFilter, categoryCritical]);

  // Register mirrors the uploaded file's own columns (fallback: canonical labels).
  const columns = useMemo(
    () => files.lineList?.rawHeaders?.length
      ? files.lineList.rawHeaders
      : LINE_LIST_FIELDS.filter(f => f.required).map(f => f.label),
    [files.lineList]);
  const labelToKey = useMemo(
    () => Object.fromEntries(LINE_LIST_FIELDS.map(f => [f.label, f.key])), []);

  if (!files.lineList) return <EmptyState />;

  return (
    <div className="space-y-4">
      {/* KPI row */}
      <div className="grid grid-cols-2 md:grid-cols-5 gap-3">
        {[
          ['Total lines', kpis.total, 'var(--rd-text)'],
          ['Stress critical', kpis.critical, 'var(--rd-danger)'],
          ['Matched', kpis.matched, 'var(--rd-success)'],
          ['Missing criticality', kpis.missing, 'var(--rd-danger)'],
          ['Open review items', kpis.review, 'var(--rd-warning)'],
        ].map(([label, value, color]) => (
          <div key={label} className="rd-card rd-kpi">
            <div className="rd-kpi-value" style={{ color }}>{value}</div>
            <div className="rd-kpi-label">{label}</div>
          </div>
        ))}
      </div>

      {!files.stress && (
        <div className="rd-banner rd-banner-info">
          Stress Criticality auto-generated by RADAI (AGES-SP-09-004 Table 7.1 + Sec. 7.3). Upload a Stress Criticality file to reconcile against the stress engineer's assessment.
        </div>
      )}

      {/* Filter chips + export */}
      <div style={{ display: 'flex', gap: '0.5rem', flexWrap: 'wrap', alignItems: 'center' }}>
        {matchFilter && (
          <span className="rd-pill rd-pill-info" style={{ display: 'inline-flex', alignItems: 'center', gap: 6 }}>
            Match status: {matchFilter.label}
            <button onClick={clearUrlFilters} aria-label="Remove match filter"
              style={{ background: 'none', border: 'none', padding: 0, cursor: 'pointer', color: 'inherit', fontWeight: 700 }}>✕</button>
          </span>
        )}
        {categoryCritical && (
          <span className="rd-pill rd-pill-danger" style={{ display: 'inline-flex', alignItems: 'center', gap: 6 }}>
            Category: Stress critical
            <button onClick={clearUrlFilters} aria-label="Remove category filter"
              style={{ background: 'none', border: 'none', padding: 0, cursor: 'pointer', color: 'inherit', fontWeight: 700 }}>✕</button>
          </span>
        )}
        {CHIPS.map(c => (
          <button key={c} onClick={() => setChip(c)}
            className={`rd-btn rd-btn-sm ${chip === c ? 'rd-btn-primary' : 'rd-btn-secondary'}`}>
            {c}
          </button>
        ))}
        <span style={{ flex: 1 }} />
        <button className="rd-btn rd-btn-secondary rd-btn-sm"
          onClick={() => exportRegisterWorkbook(filtered, columns, { revision: files.lineList?.revision })}>
          Export (.xlsx)
        </button>
      </div>

      {/* Table — mirrors the uploaded Process Line List columns; Stress Category is the last column */}
      <div className="rd-card" style={{ overflow: 'auto', maxHeight: '62vh' }}>
        <table className="rd-table">
          <thead>
            <tr>
              {columns.map(h => <th key={h}>{h}</th>)}
              <th>Stress Category</th><th></th>
            </tr>
          </thead>
          <tbody>
            {filtered.map(l => (
              <tr key={l._key} style={{ cursor: 'pointer' }} onClick={() => setSelected(l)}>
                {columns.map((h, i) => (
                  <td key={h} className={i === 0 ? 'rd-mono' : undefined}
                    style={i === 0 ? { color: 'var(--rd-accent)', fontWeight: 500 } : undefined}>
                    {l._raw?.[h] ?? l[labelToKey[h]] ?? ''}
                  </td>
                ))}
                <td><span className={`rd-pill ${CAT_PILL[l.stress_category] || 'rd-pill-neutral'}`}
                  title={l.category_mismatch ? `File: ${l.file_category} · RADAI: ${l.generated_category}` : (l.generated_category ? `RADAI (Size × Temp): ${l.generated_category}` : undefined)}
                  >{l.stress_category}</span>
                  {l.category_mismatch && <span style={{ color: 'var(--rd-warning)', fontSize: 'var(--rd-text-caption)', marginLeft: 4 }} title="File level differs from RADAI allocation">≠</span>}
                </td>
                <td><button className="rd-btn rd-btn-ghost rd-btn-sm" onClick={e => { e.stopPropagation(); setSelected(l); }}>Open</button></td>
              </tr>
            ))}
            {filtered.length === 0 && (
              <tr><td colSpan={columns.length + 2} style={{ textAlign: 'center', padding: '2rem', color: 'var(--rd-text-faint)' }}>
                No lines match the active filters
              </td></tr>
            )}
          </tbody>
        </table>
      </div>

      <LineDrawer line={selected} onClose={() => setSelected(null)} />
    </div>
  );
}
