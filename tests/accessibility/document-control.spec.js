const region = (page, name) => page.getByRole('region', { name, exact: true })
const register = page => region(page, 'Document register')
const details = page => region(page, 'Document details')
const indicators = page => page.locator('.dc-kpis')
const downloadFile = page => details(page).locator('.dc-document-file').getByRole('button', { name: /^Download / })
const search = page => page.getByRole('searchbox', { name: 'Search document title or file', exact: true })
const select = (page, name) => page.getByRole('combobox', { name, exact: true })
const addMenu = page => page.locator('summary[aria-label="Add document"]')

async function loaded(page) {
  await expect(page.getByRole('heading', { name: 'Project Documents', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Management', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.pp-header-actions').getByRole('button', { name: 'Refresh', exact: true })).toBeEnabled()
}
async function noOverflow(page) {
  const result = await page.evaluate(() => ({ viewport: innerWidth, document: document.documentElement.scrollWidth }))
  expect(result.document, JSON.stringify(result)).toBeLessThanOrEqual(result.viewport + 1)
}
async function accessible(page, selector = '.project-performance-workspace') {
  const scan = await new AxeBuilder({ page }).include(selector).analyze()
  expect(scan.violations.filter(item => ['serious', 'critical'].includes(item.impact))).toEqual([])
}
async function selectMatching(locator, pattern) {
  const option = locator.getByRole('option').filter({ hasText: pattern }).first()
  await locator.selectOption(await option.evaluate(element => element.value))
}
async function pickDocument(page, title) {
  await search(page).fill(title)
  await register(page).getByRole('button', { name: `Select document ${title}`, exact: true }).click()
  await expect(details(page)).toContainText(title)
  await expect(details(page).getByRole('button', { name: 'Edit metadata', exact: true })).toBeVisible()
}
async function uploadDialog(page) {
  await addMenu(page).click()
  await page.getByRole('button', { name: 'New document', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'New document', exact: true })
  await expect(dialog).toBeVisible()
  return dialog
}
async function captureDownload(page, trigger) {
  const pending = page.waitForEvent('download')
  await trigger()
  const download = await pending
  return { filename: download.suggestedFilename(), body: await readFile(await download.path()) }
}

