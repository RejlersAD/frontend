test('upload title and type editing authenticated download and confirmed deletion persist actual records', async ({ page }) => {
  const state = await documentHarness(page)
  await loaded(page)
  let dialog = await uploadDialog(page)
  await dialog.getByLabel('Document file', { exact: true }).setInputFiles(documentUpload())
  await dialog.getByRole('textbox', { name: 'Document title', exact: true }).fill('Vendor clarification note')
  await select(dialog, 'Document type').selectOption('minutes')
  await dialog.getByRole('button', { name: 'Upload document', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  const created = state.records[17].documents.find(item => item.title === 'Vendor clarification note')
  expect(created).toMatchObject({ project: 17, kind: 'minutes', parse_status: 'queued', original_filename: 'Vendor-review-note.txt' })
  await expect(details(page)).toContainText('Vendor clarification note')
  await details(page).getByRole('button', { name: 'Edit metadata', exact: true }).click()
  dialog = page.getByRole('dialog', { name: 'Edit document', exact: true })
  await dialog.getByRole('textbox', { name: 'Document title', exact: true }).fill('Approved meeting title')
  await select(dialog, 'Document type').selectOption('other')
  await dialog.getByRole('button', { name: 'Save document', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  expect(state.writes.at(-1)).toMatchObject({ method: 'PATCH', body: { title: 'Approved meeting title', kind: 'other' } })
  expect(Object.keys(state.writes.at(-1).body).sort()).toEqual(['kind', 'title'])
  const download = await captureDownload(page, () => downloadFile(page).click())
  expect(download.filename).toBe('Vendor-review-note.txt')
  expect(download.body.toString()).toContain('Recorded equipment clarification')
  expect(state.requests.some(item => item.path.endsWith(`/documents/${created.id}/download/`))).toBe(true)
  await details(page).getByRole('button', { name: 'Delete', exact: true }).click()
  dialog = page.getByRole('dialog', { name: 'Delete document', exact: true })
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  expect(state.records[17].documents.some(item => item.id === created.id)).toBe(true)
  await details(page).getByRole('button', { name: 'Delete', exact: true }).click()
  await dialog.getByRole('button', { name: 'Confirm deletion', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  expect(state.records[17].documents.some(item => item.id === created.id)).toBe(false)
  expect(state.writes.at(-1).method).toBe('DELETE')
})

