test('failed activity save keeps edits then the reviewed revision is submitted and published', async ({ page }) => {
  const state = await open(page)
  await workspace(page).getByRole('button', { name: registerNames[0], exact: true }).click()
  await page.getByRole('complementary', { name: 'Activity details', exact: true }).getByRole('button', { name: 'Edit activity', exact: true }).click()
  const editor = page.getByRole('dialog', { name: 'Edit task', exact: true })
  await editor.getByLabel('Duration (working days)', { exact: true }).fill('4')
  state.saveError = { error: 'The plan changed in another session. Your edits have not been saved.', code: 'simple_plan_revision_conflict' }
  await editor.getByRole('button', { name: 'Save task', exact: true }).click()
  await expect(editor.getByRole('alert')).toContainText('Your edits have not been saved')
  await expect(editor.getByLabel('Duration (working days)', { exact: true })).toHaveValue('4')
  expect(state.records[17].simplePlan.revision).toBe(4)
  state.saveError = null
  await editor.getByRole('button', { name: 'Save task', exact: true }).click()
  await expect(editor).toHaveCount(0)
  expect(state.records[17].simplePlan.revision).toBe(5)
  expect(simpleWrites(state).filter(item => item.method === 'PUT').map(item => item.data.revision)).toEqual([4, 4])
  expect(state.records[17].simplePlan.tasks[0].title).toBe(registerNames[0])
  await workspace(page).getByRole('button', { name: 'Review & approve', exact: true }).click()
  const approval = page.getByRole('dialog', { name: 'Review & publish baseline', exact: true })
  await expect(approval).toBeVisible()
  await approval.getByRole('combobox', { name: 'Plan approver', exact: true }).selectOption('7')
  await approval.getByRole('button', { name: 'Submit for approval', exact: true }).click()
  await expect(approval.getByRole('button', { name: 'Approve & publish baseline', exact: true })).toBeEnabled()
  expect(simpleWrites(state).find(item => item.path.endsWith('/submit/')).data).toEqual({ revision: 5, approver_id: 7 })
  await approval.getByRole('button', { name: 'Approve & publish baseline', exact: true }).click()
  await expect(approval.getByRole('heading', { name: 'Baseline published', exact: true })).toBeVisible()
  expect(simpleWrites(state).find(item => item.path.endsWith('/approve-publish/')).data).toEqual({ revision: 6 })
  await approval.getByRole('button', { name: 'Close Review & publish baseline', exact: true }).click()
  await expect(await scheduleActionButton(page, 'Add activity')).toBeDisabled()
  await scheduleAction(page, 'New version')
  await expect(await scheduleActionButton(page, 'Add activity')).toBeEnabled()
  await closeScheduleMenu(page, 'Schedule actions')
  expect(simpleWrites(state).find(item => item.path.endsWith('/reopen/')).data).toEqual({ revision: 7 })
  expect(state.records[17].simplePlan.baseline.name).toBe('Approved Phase 1 baseline')
  clean(state)
})

