test.setTimeout(60000)
const workspace = page => page.getByRole('region', { name: 'Master schedule workspace', exact: true })
const inputs = page => page.getByRole('dialog', { name: 'Documents & project inputs', exact: true })
const simpleWrites = state => state.writes.filter(item => item.path.includes('/simple-plan/'))
const clean = state => { expect(state.pageErrors).toEqual([]); expect(state.unknownWrites).toEqual([]); expect(state.unknown).toEqual([]) }
async function open(page, options) {
  const state = await masterScheduleHarness(page, options)
  await expect(workspace(page).getByRole('heading', { name: 'Master Schedule', exact: true })).toBeVisible()
  return state
}
async function projectInputs(page) {
  await scheduleAction(page, 'Project inputs')
  await expect(inputs(page)).toBeVisible()
  return inputs(page)
}
async function setDates(dialog) {
  await expect(dialog.getByLabel('Project start date', { exact: true })).toBeEnabled()
  await dialog.getByLabel('Project start date', { exact: true }).fill('2026-09-21')
  await dialog.getByLabel('Project end date', { exact: true }).fill('2026-12-20')
}

