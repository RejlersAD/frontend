test('Create PO validates the selected folder on click and preserves its project through a matching PR', async ({ page }) => {
  const state = await open(page)
  await project(page).click()
  expect(writes(state)).toEqual([])
  await page.getByRole('button', { name: 'Create PO', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'New purchase order', exact: true })).toBeVisible()
  expect(state.preparations).toEqual([{ scope_id: 'folder-17', expected_folder_project_id: '17' }])
  await expect(page.locator('#po-project-search')).toHaveValue(/5900985/)
  await page.locator('#po-pr-search').fill('9001')
  await page.getByRole('option', { name: new RegExp(orderFormRecommendation.pr_number) }).click()
  await expect(page.getByLabel('PO Number', { exact: true })).toHaveValue(orderFormNumber)
  await expect(page.locator('#po-project-search')).toHaveValue(/5900985/)
  expect(state.requests.filter(row => row.path.endsWith('/create-project/'))).toEqual([])
  await page.getByRole('combobox', { name: 'Price basis', exact: true }).selectOption('exclusive')
  await page.locator('.purchase-order-form-workspace').getByRole('button', { name: /^Save draft$/i }).first().click()
  await expect(page.getByRole('heading', { name: 'New purchase order', exact: true })).toHaveCount(0)
  await expect(page).toHaveURL(/\/procurement\/projects\/reconciliation$/)
  expect(state.acceptedWrites).toHaveLength(1)
  expect(state.record).toMatchObject({ enterprise_project: '17', project_number: '5900985', pr_reference: orderFormRecommendation.id })
  checkClean(state)
})

