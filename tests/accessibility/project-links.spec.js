import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { projectLinksHarness } from '../fixtures/project-links.fixture'
import { orderFormNumber, orderFormRecommendation } from '../fixtures/purchase-order-form.fixture'

test.setTimeout(120000)
test.use({ serviceWorkers: 'block', viewport: { width: 1672, height: 941 } })
const projects = page => page.getByRole('region', { name: 'Projects', exact: true })
const orders = page => page.getByRole('region', { name: 'Purchase orders', exact: true })
const project = (page, code = '5900985') => projects(page).getByRole('button').filter({ hasText: code })
const connect = page => page.getByRole('button', { name: 'Connect PO to project', exact: true })
const selectPO = (page, number = 'PO-2026-0048') => orders(page).getByRole('button', { name: `Select ${number}`, exact: true }).click()
const open = async (page, options) => {
  const state = await projectLinksHarness(page, options)
  await expect(page.getByRole('heading', { name: 'Project Links', exact: true })).toBeVisible()
  await expect(project(page)).toBeVisible()
  return state
}
const checkClean = state => { expect(state.unknown).toEqual([]); expect(state.pageErrors).toEqual([]) }
const writes = state => state.requests.filter(row => ['POST', 'PATCH', 'PUT', 'DELETE'].includes(row.method) && row.path.includes('/procurement/'))

test('simple split workspace lists every server project folder and selection is read-only', async ({ page }) => {
  const state = await open(page)
  await expect(projects(page).getByRole('button')).toHaveCount(54)
  await expect(connect(page)).toBeDisabled()
  await project(page).click()
  await selectPO(page)
  await expect(connect(page)).toBeEnabled()
  await expect(page.getByRole('checkbox', { name: /reviewed/ })).toHaveCount(0)
  await expect(page.getByRole('combobox', { name: /Reason/ })).toHaveCount(0)
  await expect(page.getByRole('link', { name: 'Advanced reconciliation' })).toHaveAttribute('href', '/procurement/projects/reconciliation/advanced')
  const left = await projects(page).boundingBox(), right = await orders(page).boundingBox()
  expect(left.x + left.width).toBeLessThan(right.x)
  const button = await connect(page).boundingBox()
  expect(button.y + button.height).toBeLessThan(942)
  expect(writes(state)).toEqual([])
  await page.screenshot({ path: '../artifacts/project-links-desktop.png', fullPage: true })
  const a11y = await new AxeBuilder({ page }).include('.project-links-workspace').analyze()
  expect(a11y.violations).toEqual([])
  checkClean(state)
})

test('explicit Connect saves only the selected PO and folder with both current project guards', async ({ page }) => {
  const state = await open(page)
  const before = state.linkOrders.map(({ id, po_number, total_amount, currency }) => ({ id, po_number, total_amount, currency }))
  await project(page).click(); await selectPO(page); await connect(page).click()
  await expect(page.locator('.plw-success[role="status"]')).toContainText('PO-2026-0048 is connected')
  expect(state.connections).toEqual([{ scope_id: 'folder-17', order_id: 'order-1', expected_project_id: null, expected_folder_project_id: '17' }])
  expect(state.preparations).toEqual([])
  expect(state.linkOrders.map(({ id, po_number, total_amount, currency }) => ({ id, po_number, total_amount, currency }))).toEqual(before)
  await expect(orders(page).getByRole('button', { name: "Selected project's POs", exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('button', { name: 'Connected', exact: true })).toBeDisabled()
  checkClean(state)
})

