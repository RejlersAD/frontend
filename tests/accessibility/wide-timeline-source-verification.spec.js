async function panes(page) {
  return grid(page).locator('.p6-heading').evaluate(element => {
    const table = element.querySelector('.p6-left-clip').getBoundingClientRect()
    const timeline = element.querySelector('.p6-right-clip').getBoundingClientRect()
    return { table: table.width, timeline: timeline.width, ratio: timeline.width / (table.width + timeline.width + 6) }
  })
}

test('desktop timeline receives approximately 60% width while project tabs and activity columns remain accessible', async ({ page }) => {
  await page.setViewportSize({ width: 1900, height: 950 })
  const state = await open(page, { realShell: true })
  const before = await panes(page)
  expect(before.ratio).toBeGreaterThan(.58)
  expect(before.ratio).toBeLessThan(.61)
  expect((await page.locator('.compact-real-shell').boundingBox()).x).toBe(198)
  const areas = page.getByRole('navigation', { name: 'Project work areas', exact: true })
  for (const name of ['Overview', 'Schedule', 'Cost & Commercial', 'Milestones', 'Risks & Changes', 'Estimates', 'Documents', 'Activity & Audit']) await expect(areas.getByRole('button', { name, exact: true })).toBeVisible()
  await page.locator('summary[aria-label="More project actions"]').click()
  await expect(page.locator('.pd-menu').getByRole('button', { name: 'EPC lifecycle', exact: true })).toBeVisible()
  await page.locator('summary[aria-label="More project actions"]').click()
  await expect(page.getByRole('combobox', { name: 'Project section', exact: true })).toHaveCount(0)
  const scroll = grid(page).getByLabel('Scroll activity columns', { exact: true })
  const maximumScroll = await scroll.evaluate(element => Math.max(0, element.scrollWidth - element.clientWidth))
  await scroll.evaluate(element => { element.scrollLeft = element.scrollWidth; element.dispatchEvent(new Event('scroll')) })
  await expect.poll(async () => Math.abs(await scroll.evaluate(element => element.scrollLeft) - maximumScroll)).toBeLessThanOrEqual(1)
  const pane = await grid(page).locator('.p6-heading .p6-left-clip').boundingBox()
  for (const name of ['Duration', 'Start', 'Finish', 'Total Float']) {
    const heading = grid(page).getByRole('columnheader', { name, exact: true })
    const box = await heading.boundingBox()
    expect(box.x).toBeGreaterThanOrEqual(pane.x - 1)
    expect(box.x + box.width).toBeLessThanOrEqual(pane.x + pane.width + 1)
  }
  await scroll.evaluate(element => { element.scrollLeft = 0; element.dispatchEvent(new Event('scroll')) })
  await page.screenshot({ path: '../artifacts/wide-timeline-desktop.png', animations: 'disabled' })
  clean(state)
})

test('timeline focus restores the chosen split and manual keyboard or pointer resize exits focus', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  const state = await open(page)
  await expect(focusToggle(page)).toHaveAttribute('aria-pressed', 'false')
  const initial = await panes(page)
  await splitter(page).focus(); await page.keyboard.press('Shift+ArrowRight')
  const saved = await panes(page)
  expect(saved.table).toBeCloseTo(initial.table + 60, 0)
  await focusToggle(page).click()
  await expect(grid(page)).toHaveAttribute('data-timeline-focus', 'true')
  expect((await panes(page)).table).toBe(280)
  expect((await panes(page)).timeline).toBeGreaterThan(saved.timeline)
  await focusToggle(page).click()
  expect((await panes(page)).table).toBeCloseTo(saved.table, 0)
  await focusToggle(page).click()
  await splitter(page).focus(); await page.keyboard.press('ArrowRight')
  await expect(focusToggle(page)).toHaveAttribute('aria-pressed', 'false')
  expect((await panes(page)).table).toBe(300)
  await focusToggle(page).click()
  const drag = await splitter(page).boundingBox()
  await page.mouse.move(drag.x + 3, drag.y + 20); await page.mouse.down()
  await page.mouse.move(drag.x + 103, drag.y + 20, { steps: 4 }); await page.mouse.up()
  await expect(focusToggle(page)).toHaveAttribute('aria-pressed', 'false')
  expect((await panes(page)).table).toBeCloseTo(380, 0)
  await focusToggle(page).click(); await focusToggle(page).click()
  expect((await panes(page)).table).toBeCloseTo(380, 0)
  await splitter(page).dblclick()
  expect((await panes(page)).table).toBeCloseTo(initial.table, 0)
  clean(state)
})

