test('220 exact register matches never certify source schedule dates, durations or calendar', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  const state = await open(page, { verification: 'missing_reference' })
  const before = structuredClone(state.records[17].simplePlan)
  const trigger = scheduleWorkspace(page).getByRole('button', { name: 'Verify schedule sources', exact: true })
  await expect(trigger).toHaveText('Unverified')
  await trigger.click()
  const dialog = page.getByRole('dialog', { name: 'Source verification', exact: true })
  await expect(dialog).toBeVisible()
  const register = dialog.getByRole('region', { name: 'Document register comparison', exact: true })
  await expect(register).toContainText('Exact register match')
  await expect(register).toContainText('220 of 220 parsed rows match')
  await expect(register).toContainText('This confirms register content only.')
  const summary = dialog.getByRole('region', { name: 'Current calculated summary', exact: true })
  await expect(summary).toContainText('193 working days')
  await expect(summary.locator('dl > div').filter({ has: page.getByText('Original schedule duration', { exact: true }) })).toContainText('Not verified')
  const checks = dialog.getByRole('region', { name: 'Schedule source checks', exact: true })
  await expect(checks).toContainText('Schedule unverified')
  await expect(checks).toContainText('No original reference schedule is uploaded.')
  for (const label of ['Dates compared with source', 'Dependencies compared with source']) await expect(checks.locator('dl > div').filter({ has: page.getByText(label, { exact: true }) })).toContainText('Not verified')
  await expect(checks.locator('dl > div').filter({ has: page.getByText('Verified source dates', { exact: true }) })).toContainText('0')
  await expect(checks).toContainText('220 proposed durations')
  await expect(checks).toContainText('4 inferred predecessor links')
  await expect(checks).toContainText('The original schedule calendar and its exceptions have not been verified.')
  const requirements = dialog.getByRole('region', { name: 'Source requirements', exact: true })
  await expect(requirements).toContainText(verificationScopeMessage)
  await expect(requirements).toContainText('Anchor unconfirmed')
  await expect(requirements).toContainText('Scope of Work.pdf · Page 14')
  await expect(dialog.getByRole('button', { name: /^(Save|Approve|Confirm|Import)$/ })).toHaveCount(0)
  const bounds = await dialog.boundingBox()
  expect(Math.abs(bounds.x + bounds.width / 2 - 720)).toBeLessThan(2)
  const scan = await new AxeBuilder({ page }).include('.psv-dialog').analyze()
  expect(scan.violations.filter(item => ['serious', 'critical'].includes(item.impact))).toEqual([])
  await page.screenshot({ path: '../artifacts/schedule-source-verification.png', animations: 'disabled' })
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await scheduleAction(page, 'Verify sources')
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: 'Project inputs', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('dialog', { name: 'Documents & project inputs', exact: true })).toBeVisible()
  expect(state.records[17].simplePlan).toEqual(before)
  clean(state)
})

